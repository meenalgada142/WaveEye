if __name__ == "__main__":
    import sys

    if len(sys.argv) < 2:
        print("Usage: python ir_backtracking.py <ir.json>")
        sys.exit(1)

    ir_json = sys.argv[1]
    base = Path(ir_json).stem

    print(f"[IR] Loading {ir_json}")
    ir = load_ir_json(ir_json)

    print("[IR] Building drivers")
    drivers = build_drivers_from_ir(ir)

    print("[IR] Detecting aliases")
    alias_engine = build_aliases(drivers)

    csv_out = f"{base}_backtracking.csv"
    json_out = f"{base}_backtracking.json"

    print("[OUT] Writing CSV")
    save_backtracking_csv(drivers, alias_engine, csv_out)

    print("[OUT] Writing JSON")
    save_backtracking_json(drivers, alias_engine, json_out)

    print(f"[DONE] Generated:")
    print(f"  - {csv_out}")
    print(f"  - {json_out}")


def run_ir_backtracking(ir_json_path, out_csv, out_json):
    with open(ir_json_path) as f:
        ir = json.load(f)

    drivers = build_drivers_from_ir(ir)

    alias_engine = AliasEngine()
    for lhs, drvs in drivers.items():
        for d in drvs:
            rhs = d["rhs"]
            if re.fullmatch(r'[a-zA-Z_]\w*', rhs):
                alias_engine.add_alias(lhs, rhs)

    save_backtracking_csv(drivers, alias_engine, out_csv)
    save_backtracking_json(drivers, alias_engine, out_json)